explorer_ui <- function(agency_id) {
  bslib::page_sidebar(
    title = "IMF Explorer",
    sidebar = bslib::sidebar(width = 340,
      shiny::h4("Current query"), shiny::uiOutput("summary"),
      shiny::actionButton("clear_query", "Clear current query", icon = shiny::icon("eraser")),
      shiny::hr(), shiny::fileInput("import", "Restore query JSON", accept = ".json"),
      shiny::helpText("Metadata are requested on demand. Observations are fetched only with Retrieve data.")),
    # DT's proxy search API needs its native search element in the DOM.
    shiny::tags$style(".imf-hidden-filter { display: none; }"),
    bslib::navset_card_tab(id = "stage",
      bslib::nav_panel("1 \u00b7 Dataset", value = "dataset",
        shiny::fluidRow(shiny::column(6, shiny::textInput("agency", "Agency ID", agency_id)),
          shiny::column(6, shiny::br(), shiny::actionButton("load", "Load / refresh catalogue"),
            shiny::actionButton("reset", "Reset"))),
        shiny::actionButton("refresh", "Clear metadata cache / refresh selected dataset"),
        shiny::textInput("dataset_search", "Search datasets", placeholder = "Search dataset IDs, names, descriptions or versions"),
        shiny::uiOutput("catalog_status"), DT::DTOutput("datasets"),
        shiny::helpText("Search IDs, names, descriptions or versions; select one row."),
        shiny::uiOutput("metadata")),
      bslib::nav_panel("2 \u00b7 Dimensions", value = "dimensions",
        shiny::actionButton("update", "Update available values"),
        shiny::helpText("Select dimensions in any order. Update sends the other dimensions\u2019 current filters for each code list. Empty selections are unrestricted. Remove individual items with their x buttons, clear a dimension, or select all available codes. Unavailable selections are retained and flagged."),
        shiny::uiOutput("dimension_controls")),
      bslib::nav_panel("3 \u00b7 Time", value = "time",
        shiny::radioButtons("time_mode", "Time filter", c("All periods" = "all", "Period range" = "range", "Latest N per series" = "latest")),
        shiny::conditionalPanel("input.time_mode == 'range'",
          shiny::textInput("start", "Start (optional)", placeholder = "2020 or 2020-Q1 or 2020-01"),
          shiny::textInput("end", "End (optional)", placeholder = "2025-12")),
        shiny::conditionalPanel("input.time_mode == 'latest'", shiny::numericInput("latest", "Latest N observations per series", 12, min = 1, step = 1)),
        shiny::helpText("Time modes are mutually exclusive: latest N ignores the inactive range fields. Bounds accept YYYY, YYYY-Qn, YYYY-MM or YYYY-MM-DD. N is per series, not a total row limit."),
        shiny::textInput("attributes", "Optional attribute IDs (comma separated)", placeholder = "Exact IDs from this dataset, e.g. UNIT_MEASURE"),
        shiny::helpText("Attributes are dataset-specific. Unknown IDs produce an API error; none are requested by default.")),
      bslib::nav_panel("4 \u00b7 Review", value = "review",
        shiny::uiOutput("validation"), shiny::h4("Runnable R code"),
        shiny::tags$pre(style = "white-space:pre-wrap;", shiny::textOutput("code")),
        shiny::downloadButton("script", "Download R script"),
        shiny::downloadButton("config", "Download query JSON")),
      bslib::nav_panel("5 \u00b7 Retrieve & export", value = "retrieve",
        shiny::uiOutput("breadth"), shiny::checkboxInput("broad_ok", "I understand this may request many series / observations", FALSE),
        shiny::actionButton("retrieve", "Retrieve data", class = "btn-primary"),
        shiny::uiOutput("result_status"), DT::DTOutput("results"),
        shiny::downloadButton("csv", "CSV"), shiny::downloadButton("rds", "RDS"),
        shiny::helpText("CSV/RDS export the displayed result, including when marked as an earlier query. The script and JSON describe the current query."),
        shiny::uiOutput("plot_status"), shiny::uiOutput("plot_container"))
    )
  )
}
