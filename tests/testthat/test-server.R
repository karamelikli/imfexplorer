test_that("broad requests require acknowledgement and reset leaves no dependent state", {
  f <- fixture_api()
  shiny::testServer(explorer_server("TEST", f$api), {
    session$flushReact()
    session$setInputs(datasets_rows_selected = 1L, time_mode = "all")
    session$setInputs(dimensions_ready = 1L)
    session$setInputs(retrieve = 1L, broad_ok = FALSE)
    expect_null(rv$results)
    session$setInputs(retrieve = 2L, broad_ok = TRUE)
    expect_equal(nrow(rv$results), 2)
    session$setInputs(reset = 1L)
    expect_null(rv$dataset)
    expect_null(rv$dimensions)
    expect_identical(rv$values, list())
    expect_null(rv$results)
  })
})

