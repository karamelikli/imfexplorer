test_that("the main workflow is lazy, conditional, explicit and resets on dataset change", {
  f <- fixture_api()
  shiny::testServer(explorer_server("TEST", f$api), {
    session$flushReact()
    expect_length(f$log$calls, 1)
    expect_identical(f$log$calls[[1]]$kind, "datasets")
    expect_null(rv$dimensions)
    session$setInputs(datasets_rows_selected = 1L, time_mode = "latest", latest = 2)
    session$flushReact()
    expect_identical(non_time()$id, c("REGION", "METRIC"))
    expect_false(any(vapply(f$log$calls, function(x) x$kind == "data", logical(1))))
    ids <- vapply(seq_len(nrow(non_time())), control_id, character(1))
    args <- stats::setNames(list("Y", "limited"), ids)
    do.call(session$setInputs, args)
    session$setInputs(update = 1L)
    session$flushReact()
    expect_identical(query()$filters$REGION, "Y")
    expect_identical(selection_status(query()$filters$REGION, rv$values$REGION)$invalid, "Y")
    expect_match(query_problem(), "Unavailable codes")
    session$setInputs(retrieve = 1L, broad_ok = TRUE)
    expect_null(rv$results)
    args <- stats::setNames(list("X", "index"), ids)
    do.call(session$setInputs, args)
    session$setInputs(update = 2L)
    expect_null(query_problem())
    session$setInputs(retrieve = 2L, broad_ok = TRUE)
    expect_equal(nrow(rv$results), 2)
    expect_identical(rv$result_query$agency, "TEST")
    expect_identical(rv$result_query$version, "1")
    session$setInputs(latest = 3)
    expect_false(same_query(query(), rv$result_query))
    f$log$fail_data <- TRUE
    session$setInputs(retrieve = 3L, broad_ok = TRUE)
    expect_match(rv$result_error, "fixture data failure")
    expect_equal(nrow(rv$results), 2)
    session$setInputs(datasets_rows_selected = 2L)
    expect_identical(non_time()$id, c("SECTOR", "FREQ"))
    expect_identical(query()$filters, list())
    expect_null(rv$results)
    expect_null(rv$result_query)
  })
})

test_that("availability failures are recoverable and successful empty values are distinct", {
  f <- fixture_api()
  shiny::testServer(explorer_server("TEST", f$api), {
    session$flushReact()
    session$setInputs(datasets_rows_selected = 1L)
    f$log$fail_values <- TRUE
    rm(list = ls(cache, all.names = TRUE), envir = cache)
    session$setInputs(update = 1L)
    expect_match(query_problem(), "API failure")
    expect_true(nrow(rv$values$REGION) > 0)
    f$log$fail_values <- FALSE
    session$setInputs(update = 2L)
    expect_null(query_problem())
    do.call(session$setInputs, stats::setNames(list("empty"), control_id(2)))
    session$setInputs(update = 3L)
    expect_equal(nrow(rv$values$REGION), 0)
    expect_match(query_problem(), "No available")
  })
})

test_that("import restores exact version and retains flagged codes", {
  f <- fixture_api()
  path <- tempfile(fileext = ".json")
  on.exit(unlink(path))
  writeLines(query_json(new_query("TEST", "A", "1", list(REGION = "missing"), last_n_obs = 2)), path)
  shiny::testServer(explorer_server("TEST", f$api), {
    session$flushReact()
    session$setInputs(import = list(datapath = path, size = file.info(path)$size))
    expect_identical(rv$seed$REGION, "missing")
    expect_identical(rv$dataset$version, "1")
    expect_identical(query()$filters$REGION, "missing")
    expect_identical(selection_status(query()$filters$REGION, rv$values$REGION)$invalid, "missing")
    # Unavailable versions do not overwrite the current dataset.
    writeLines(query_json(new_query("TEST", "A", "999")), path)
    session$setInputs(import = list(datapath = path, size = file.info(path)$size))
    expect_identical(rv$dataset$version, "1")
  })
})

